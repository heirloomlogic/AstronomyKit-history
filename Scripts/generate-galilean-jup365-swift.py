#!/usr/bin/env python3
"""Compile the qualified jup365 payloads into record-addressable Swift strings."""

import argparse
import base64
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "Scripts/jupiter-moon-data/jup365"
MANIFEST = DATA / "representation.json"
DESTINATION = ROOT / "Sources/AstronomyKit/Engine/Bodies/Generated/Jup365"
QUALIFIER_PATH = ROOT / "Scripts/generate-galilean-jup365.py"
INDEX_NAME = "Jup365Index.swift"
COMPONENTS = ("io", "europa", "ganymede", "callisto", "jupiter")
RECORDS_PER_CHUNK = 16_384

QUALIFIER_SPEC = importlib.util.spec_from_file_location("generate_galilean_jup365", QUALIFIER_PATH)
qualifier = importlib.util.module_from_spec(QUALIFIER_SPEC)
QUALIFIER_SPEC.loader.exec_module(qualifier)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def record_bytes(report):
    float32 = report["float32CoefficientCount"]
    tail = report["keptCoefficientCount"] - float32
    return 3 * (4 * float32 + 2 * tail)


def record_lines(payload, record_bytes):
    if record_bytes <= 0 or len(payload) % record_bytes:
        raise ValueError("jup365 payload does not contain whole records")
    return [base64.b64encode(payload[offset : offset + record_bytes]) for offset in range(0, len(payload), record_bytes)]


def load_inputs():
    manifest = json.loads(MANIFEST.read_bytes())
    payloads = {name: (DATA / f"{name}.bin").read_bytes() for name in COMPONENTS}
    qualifier.verify_manifest(manifest, payloads)
    return manifest, payloads


def swift_number(value):
    return repr(float(value))


def symbol(name):
    return name[0].upper() + name[1:]


def chunk_name(name, index):
    return f"Jup365{symbol(name)}{index:03d}.swift"


def render_chunk(name, index, lines, manifest_digest, payload_digest):
    records = b"\n".join(lines).decode("ascii")
    return f'''// Generated by Scripts/generate-galilean-jup365-swift.py; do not edit.
// Qualified representation SHA-256: {manifest_digest}; {name} payload SHA-256: {payload_digest}.
// swift-format-ignore-file

extension Engine.JupiterMoons.Jup365 {{
    static var {name}Chunk{index}: StaticString {{
        @inline(never) get {{ {name}Payload{index} }}
    }}
    private static var {name}Payload{index}: StaticString {{
        @inline(never) get {{
            """
{records}
"""
        }}
    }}
}}
'''.encode()


def render_index(manifest, chunks_by_component, manifest_digest):
    component_rows = []
    for name in COMPONENTS:
        report = manifest["components"][name]
        scales = ",\n                ".join("[" + ", ".join(swift_number(value) for value in axis) + "]" for axis in report["tailScales"])
        chunks = ",\n                ".join(f"{name}Chunk{index}" for index in range(chunks_by_component[name]))
        component_rows.append(
            f"""        Component(
            recordDays: {swift_number(report['recordDays'])}, recordCount: {report['recordCount']},
            sourceCoefficientCount: {report['sourceCoefficientCount']}, keptCoefficientCount: {report['keptCoefficientCount']},
            float32CoefficientCount: {report['float32CoefficientCount']}, recordBytes: {record_bytes(report)},
            tailScales: [
                {scales}
            ],
            chunks: [
                {chunks}
            ]
        )"""
        )
    rows = ",\n".join(component_rows)
    start, end = manifest["coverageJDTDB"]
    payload_digests = ",\n        ".join(f'"{manifest["components"][name]["sha256"]}"' for name in COMPONENTS)
    return f"""// Generated by Scripts/generate-galilean-jup365-swift.py; do not edit.
// Qualified representation SHA-256: {manifest_digest}.
// swift-format-ignore-file

extension Engine.JupiterMoons.Jup365 {{
    static let startJDTDB = {swift_number(start)}
    static let exclusiveEndJDTDB = {swift_number(end)}
    static let sourceSeamJDTDB = {swift_number(manifest['sourceSeamJDTDB'])}
    static let recordsPerChunk = {RECORDS_PER_CHUNK}
    static let representationSHA256 = "{manifest_digest}"
    static let payloadSHA256 = [
        {payload_digests}
    ]

    static let components: [Component] = [
{rows}
    ]
}}
""".encode()


def render(manifest, payloads):
    qualifier.verify_manifest(manifest, payloads)
    manifest_digest = digest(qualifier.encoded(manifest))
    outputs = {}
    chunks_by_component = {}
    for name in COMPONENTS:
        report = manifest["components"][name]
        lines = record_lines(payloads[name], record_bytes(report))
        chunks = [lines[offset : offset + RECORDS_PER_CHUNK] for offset in range(0, len(lines), RECORDS_PER_CHUNK)]
        chunks_by_component[name] = len(chunks)
        for index, chunk in enumerate(chunks):
            outputs[Path(chunk_name(name, index))] = render_chunk(
                name, index, chunk, manifest_digest, report["sha256"]
            )
    outputs[Path(INDEX_NAME)] = render_index(manifest, chunks_by_component, manifest_digest)
    return outputs


def verify_outputs(outputs, manifest, payloads):
    expected = render(manifest, payloads)
    if outputs != expected:
        raise ValueError("generated jup365 Swift does not reassemble the qualified payloads")
    expected_names = {Path(INDEX_NAME)} | {
        Path(chunk_name(name, index))
        for name in COMPONENTS
        for index in range((manifest["components"][name]["recordCount"] + RECORDS_PER_CHUNK - 1) // RECORDS_PER_CHUNK)
    }
    if set(outputs) != expected_names:
        raise ValueError("generated jup365 Swift inventory differs")


def atomic_write(path, data):
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def publish(destination, outputs, manifest, payloads):
    verify_outputs(outputs, manifest, payloads)
    destination.mkdir(parents=True, exist_ok=True)
    for path, data in outputs.items():
        atomic_write(destination / path, data)
    for stale in destination.glob("*.swift"):
        if stale.relative_to(destination) not in outputs:
            stale.unlink()


def check(destination, outputs):
    actual_paths = {path.relative_to(destination) for path in destination.glob("*.swift")}
    if actual_paths != set(outputs) or any((destination / path).read_bytes() != data for path, data in outputs.items()):
        raise ValueError("generated jup365 Swift differs; run --capture")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--capture", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest, payloads = load_inputs()
    outputs = render(manifest, payloads)
    if args.capture:
        publish(DESTINATION, outputs, manifest, payloads)
        print(f"Wrote {len(outputs)} compiled jup365 Swift files")
    else:
        verify_outputs(outputs, manifest, payloads)
        check(DESTINATION, outputs)
        print(f"Checked {len(outputs)} compiled jup365 Swift files")


if __name__ == "__main__":
    main()
