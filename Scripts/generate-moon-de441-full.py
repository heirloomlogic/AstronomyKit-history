#!/usr/bin/env python3
"""Generate complete binary64 Moon-minus-Earth coefficients from pinned DE441 ranges."""
import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import hashlib
import importlib.util
import importlib.util
import json
import math
from pathlib import Path
import struct
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('qualification', ROOT/'Scripts/qualify-moon-de441.py')
q = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(q)
OUTPUT = ROOT/'Sources/AstronomyKit/Engine/Moon/Generated/DE441Full'
RESOURCE_PREFIX = 'moon-de441-full-'
SPEC = importlib.util.spec_from_file_location('generated_binary_resource', ROOT/'Scripts/generated-binary-resource.py')
binary = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(binary)
MANIFEST = ROOT/'Scripts/moon-data/de441-full-evidence.json'
CHUNK = 8192
START = -1461004.5
COUNT = 730502
BINDINGS = ['Scripts/generate-moon-de441-full.py', 'Scripts/qualify-moon-de441.py', 'Scripts/assess-moon-de441.py']


def source_hashes():
    return {p: hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in BINDINGS}


def encode_records(raw):
    if not raw or len(raw) % 312:
        raise ValueError('coefficient payload is not complete 39-binary64 records')
    return '\n'.join(base64.b64encode(raw[i:i+312]).decode('ascii') for i in range(0,len(raw),312))


def decode_records(text):
    lines = text.split('\n')
    if not lines or any(len(line) != 416 for line in lines):
        raise ValueError('encoded record shape differs')
    try:
        raw = b''.join(base64.b64decode(line,validate=True) for line in lines)
    except Exception as error:
        raise ValueError('invalid encoded record') from error
    if encode_records(raw) != text:
        raise ValueError('noncanonical encoded record')
    return raw


def compose(moon, earth, midpoint):
    q.validate_record(moon,earth,midpoint)
    values = [moon[k]-earth[k] for k in range(2,41)]
    if not all(math.isfinite(v) for v in values):
        raise ValueError('nonfinite composed coefficient')
    return struct.pack('<39d',*values)


def subtraction_bounds(values):
    # A full ulp conservatively encloses each correctly rounded subtraction, including subnormals.
    errors = [math.ulp(v) for v in values]
    position = [q.up(math.fsum(errors[a*13:(a+1)*13])) for a in range(3)]
    rate = [q.up(math.fsum(q.up(errors[a*13+k]*(k*k/2)) for k in range(13))) for a in range(3)]
    return q.norm_upper(position),q.norm_upper(rate)


def render_chunk(index, raw):
    return ('// Generated by Scripts/generate-moon-de441-full.py; do not edit.\n'
            '// Complete binary64 Moon-minus-Earth coefficients in kilometres; source ranges are pinned in the manifest.\n'
            '// swift-format-ignore-file\n\n'
            'extension Engine.MoonDE441Full {\n'
            f'    static var chunk{index}: StaticString {{\n        @inline(never) get {{ payload{index} }}\n    }}\n    private static var payload{index}: StaticString {{\n        @inline(never) get {{\n            """\n{encode_records(raw)}\n"""\n        }}\n    }}\n}}\n')


def render_index(chunks):
    names=',\n'.join('        '+binary.descriptor_from_digest(row['file'][:-4],row['bytes'],row['sha256']) for row in chunks)
    return ('// Generated by Scripts/generate-moon-de441-full.py; do not edit.\n'
            '// swift-format-ignore-file\n\n'
            'extension Engine.MoonDE441Full {\n'
            f'    static let start = {START}\n    static let recordCount = {COUNT}\n'
            f'    static let recordsPerChunk = {CHUNK}\n    static let chunks: [Engine.TableResource] = [\n{names}\n    ]\n}}\n')



def coverage():
    return {'startTDBDays':START,'exclusiveEndTDBDays':START+COUNT*4,'recordDays':4,'recordCount':COUNT,'acceptedTTDays':1461000,'lowerEmissionPaddingDays':2}


def validate_manifest(manifest):
    if manifest['coverage']!=coverage() or manifest['derivedBytes']!=COUNT*312 or manifest['coefficientCount']!=COUNT*39:
        raise ValueError('manifest coverage or coefficient count differs')
    if manifest['source']['url']!=q.direct.SOURCE_URL or manifest['source']['httpIdentity']!=q.identity():
        raise ValueError('manifest source identity differs')
    for index,row in enumerate(manifest['chunks']):
        records=min(CHUNK,COUNT-index*CHUNK)
        if records<=0 or row['index']!=index or row['file']!=f'{RESOURCE_PREFIX}{index:03}.bin' or row['records']!=records or row['bytes']!=records*312:
            raise ValueError('manifest chunk layout differs')
    if len(manifest['chunks'])!=(COUNT+CHUNK-1)//CHUNK:raise ValueError('manifest chunk count differs')


def verify_embedded(manifest):
    validate_manifest(manifest)
    if manifest['sourceHashes'] != source_hashes(): raise ValueError('generator or source parser changed')
    resources={}
    total=0; digest=hashlib.sha256()
    for row in manifest['chunks']:
        raw=(binary.RESOURCE_DIRECTORY/row['file']).read_bytes()
        if len(raw)!=row['bytes'] or hashlib.sha256(raw).hexdigest()!=row['sha256']:
            raise ValueError('coefficient chunk digest differs')
        resources[row['file']]=raw
        total+=len(raw);digest.update(raw)
    if total!=COUNT*312 or digest.hexdigest()!=manifest['derivedBinary64SHA256']:
        raise ValueError('complete coefficient digest differs')
    if (OUTPUT/'MoonDE441FullIndex.swift').read_text()!=render_index(manifest['chunks']):
        raise ValueError('generated index differs')
    if {p.name for p in OUTPUT.glob('*.swift')}!={'MoonDE441FullIndex.swift'}: raise ValueError('unexpected generated files')
    binary.publish(resources,[RESOURCE_PREFIX],True)
    print(f'Verified {COUNT*39} bundled derived binary64 coefficients')


def migrate_embedded(manifest):
    resources={}
    total=0;digest=hashlib.sha256()
    for index,row in enumerate(manifest['chunks']):
        old_name=row['file']
        if old_name!=f'MoonDE441Full{index:03}.swift':raise ValueError('embedded Moon chunk inventory differs')
        source=(OUTPUT/old_name).read_text()
        raw=decode_records(source.split('"""',2)[1].strip('\n'))
        if len(raw)!=row['bytes'] or hashlib.sha256(raw).hexdigest()!=row['sha256']:raise ValueError('embedded Moon chunk differs')
        row['file']=f'{RESOURCE_PREFIX}{index:03}.bin'
        resources[row['file']]=raw;total+=len(raw);digest.update(raw)
    if total!=manifest['derivedBytes'] or digest.hexdigest()!=manifest['derivedBinary64SHA256']:raise ValueError('complete embedded Moon digest differs')
    manifest['sourceHashes']=source_hashes()
    binary.publish(resources,[RESOURCE_PREFIX],False)
    (OUTPUT/'MoonDE441FullIndex.swift').write_text(render_index(manifest['chunks']))
    for path in OUTPUT.glob('*.swift'):
        if path.name!='MoonDE441FullIndex.swift':path.unlink()
    MANIFEST.write_text(json.dumps(manifest,indent=2,sort_keys=True)+'\n')
    verify_embedded(manifest)


def generate(cache):
    pins=json.loads((ROOT/'Scripts/moon-data/de441-compact-evidence.json').read_text())['source']['retrievedByteRangesSHA256']
    if MANIFEST.exists(): pins.update(json.loads(MANIFEST.read_text())['source']['retrievedByteRangesSHA256'])
    reader=q.CachedReader(cache,pins)
    pairs=q.layout(reader); batches=list(q.batches(pairs))
    # One additional complete record covers the private two-day emission margin at the public lower endpoint.
    moon,earth,metadata,window=pairs[0]; first=window['firstRecord']-1
    padding=(metadata,first,1,[((s.first_word-1+first*41)*8,328) for s in (moon,earth)])
    batches.insert(0,padding)
    with ThreadPoolExecutor(max_workers=6) as pool:
        list(pool.map(lambda r: reader.read(*r),[r for b in batches for r in b[3]]))
    records=0;digest=hashlib.sha256();max_position=max_rate=0.0;chunks=[];buffer=bytearray()
    with tempfile.TemporaryDirectory(prefix='moon-full-') as directory:
        stage=Path(directory)
        def publish_chunk():
            raw=bytes(buffer[:CHUNK*312]);del buffer[:CHUNK*312]
            index=len(chunks);name=f'{RESOURCE_PREFIX}{index:03}.bin'
            (stage/name).write_bytes(raw)
            chunks.append({'index':index,'file':name,'records':len(raw)//312,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest()})
        for metadata,first,count,ranges in batches:
            moon_data,earth_data=[reader.read(*r) for r in ranges]
            for i in range(count):
                moon,earth=[struct.unpack_from('<41d',data,i*328) for data in (moon_data,earth_data)]
                start=metadata.start_jd_tdb+(first+i)*4-2451545
                if start!=START+records*4: raise ValueError('source record gap or duplicate')
                raw=compose(moon,earth,(start+2)*86400)
                p,v=subtraction_bounds(struct.unpack('<39d',raw));max_position=max(max_position,p);max_rate=max(max_rate,v)
                buffer.extend(raw);digest.update(raw);records+=1
                if len(buffer)>=CHUNK*312: publish_chunk()
            print(f'Qualified {records}/{COUNT} records',flush=True)
        if buffer: publish_chunk()
        if records!=COUNT: raise ValueError('incomplete source domain')
        (stage/'MoonDE441FullIndex.swift').write_text(render_index(chunks))
        manifest={'schemaVersion':1,'sourceHashes':source_hashes(),'source':{'url':q.direct.SOURCE_URL,'httpIdentity':q.identity(),'retrievedByteRangesSHA256':reader.ranges,'wholeKernelSHA256':None},'composition':'Each coefficient is binary64(target301_relative3 - target399_relative3), in that order, in kilometres. All thirteen coefficients per ICRF axis are retained. Derived coefficient bits are not original component bytes.','coverage':coverage(),'derivedBinary64SHA256':digest.hexdigest(),'derivedBytes':COUNT*312,'coefficientCount':COUNT*39,'coefficientSubtractionEnclosure':{'positionKm':max_position,'rateKmPerTDBDay':max_rate,'method':'For every record, sum one ulp per rounded derived coefficient, weighted by n^2/2 for rate, then outward-rounded Euclidean norm. Bounds concern composition of the original binary64 component polynomials, not evaluation roundoff or physical accuracy.'},'chunks':chunks}
        # Every source record and candidate file has been validated before replacing generated outputs.
        OUTPUT.mkdir(parents=True,exist_ok=True)
        (OUTPUT/'MoonDE441FullIndex.swift').write_bytes((stage/'MoonDE441FullIndex.swift').read_bytes())
        for path in OUTPUT.glob('*.swift'):
            if path.name!='MoonDE441FullIndex.swift':path.unlink()
        binary.publish({row['file']:(stage/row['file']).read_bytes() for row in chunks},[RESOURCE_PREFIX],False)
        MANIFEST.write_text(json.dumps(manifest,indent=2,sort_keys=True)+'\n')
    verify_embedded(manifest)



def verify_source(cache):
    manifest=json.loads(MANIFEST.read_text())
    verify_embedded(manifest)
    reader=q.CachedReader(cache,manifest['source']['retrievedByteRangesSHA256'])
    pairs=q.layout(reader); batches=list(q.batches(pairs))
    moon,earth,metadata,window=pairs[0];first=window['firstRecord']-1
    batches.insert(0,(metadata,first,1,[((s.first_word-1+first*41)*8,328) for s in (moon,earth)]))
    index=0;active=-1;decoded=None
    for metadata,first,count,ranges in batches:
        components=[reader.read(*r) for r in ranges]
        for i in range(count):
            chunk=index//CHUNK
            if chunk!=active:
                decoded=(binary.RESOURCE_DIRECTORY/manifest['chunks'][chunk]['file']).read_bytes();active=chunk
            original=[struct.unpack_from('<41d',data,i*328) for data in components]
            expected=struct.pack('<39d',*[original[0][k]-original[1][k] for k in range(2,41)])
            offset=(index%CHUNK)*312
            if decoded[offset:offset+312]!=expected:
                raise ValueError(f'coefficient bits differ from pinned source record {index}')
            index+=1
    if index!=COUNT or reader.ranges!=manifest['source']['retrievedByteRangesSHA256']:
        raise ValueError('source replay is incomplete')
    print(f'Independently replayed source subtraction and all {index*39} stored coefficient bits')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--verify-source',action='store_true')
    parser.add_argument('--migrate-embedded',action='store_true')
    parser.add_argument('--cache',type=Path,default=ROOT/'.context/issue-251/ranges')
    args=parser.parse_args()
    if args.migrate_embedded:migrate_embedded(json.loads(MANIFEST.read_text()))
    elif args.verify_source: verify_source(args.cache)
    elif args.check: verify_embedded(json.loads(MANIFEST.read_text()))
    else: generate(args.cache)


if __name__=='__main__':main()
