#!/usr/bin/env python3
"""Embed pinned Saturn center coefficients; own only Planets/Generated/Saturn."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'Sources/AstronomyKit/Engine/Planets/Generated/Saturn'
MANIFEST=ROOT/'Scripts/saturn-data/assessment.json'
BODIES={6:'barycenter',10:'sun',699:'offset'}
spec=importlib.util.spec_from_file_location('packed_generator',ROOT/'Scripts/packed-table-payload.py')
common=importlib.util.module_from_spec(spec);spec.loader.exec_module(common)
RESOURCE_PREFIX='saturn-'
binary_spec=importlib.util.spec_from_file_location('generated_binary_resource',ROOT/'Scripts/generated-binary-resource.py')
binary=importlib.util.module_from_spec(binary_spec);binary_spec.loader.exec_module(binary)


def render(data,name,body):
    resource_name=RESOURCE_PREFIX+name
    return f'''// Generated by Scripts/generate-saturn-tables.py; do not edit.
// Source and SHA-256: Scripts/saturn-data/assessment.json.
// swift-format-ignore-file

extension Engine.SaturnEphemeris {{
    static let {name} = Table(
        start: {body['startJDTDB']-2451545!r}, days: {body['recordDays']!r},
        recordCount: {body['recordCount']}, coefficientCount: {body['coefficientCount']},
        scalarBytes: {4 if body['encoding']=='float32' else 8},
        resource: {binary.descriptor(resource_name,data)}
    )
}}
''',resource_name+'.bin'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--binaries',type=Path,default=ROOT/'.context/issue-92/saturn-assessment')
    args=parser.parse_args()
    candidate=json.loads(MANIFEST.read_bytes())['candidates']['float64']
    expected_paths = {OUTPUT/f'Saturn{name.title()}Data.swift' for name in BODIES.values()}
    existing_paths = set(OUTPUT.rglob('*.swift'))
    if args.check and existing_paths != expected_paths:
        raise SystemExit('generated Saturn file set differs')
    rendered,resources = {},{}
    for target,name in BODIES.items():
        body=candidate['bodies'][str(target)]
        path=OUTPUT/f'Saturn{name.title()}Data.swift'
        resource_name=RESOURCE_PREFIX+name+'.bin'
        data=(binary.RESOURCE_DIRECTORY/resource_name).read_bytes() if args.check else (args.binaries/f'float64-{target}.bin').read_bytes()
        common.validate(data,body)
        if len(data)!=body['recordCount']*3*body['coefficientCount']*(4 if body['encoding']=='float32' else 8):
            raise ValueError('Saturn coefficient layout differs')
        expected,resource_name=render(data,name,body)
        resources[resource_name]=data
        if args.check:
            if path.read_text()!=expected: raise SystemExit('generated Saturn table differs')
        else:
            rendered[path] = expected
    if not args.check:
        # Validate every input before replacing or retiring an owned output.
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for path, expected in rendered.items():
            path.write_text(expected)
        for path in existing_paths - expected_paths:
            path.unlink()
    binary.publish(resources,[RESOURCE_PREFIX],args.check)
    print('Verified Saturn tables' if args.check else 'Wrote Saturn tables')

if __name__=='__main__': main()
